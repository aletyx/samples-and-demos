#!/usr/bin/env bash
# Serves the Flutter app in web mode on http://localhost:${FLUTTER_WEB_PORT}/app/.
# The app lives under /app/, leaving the site root free for other pages.
# Runs via `devbox services up` (see process-compose.yaml) or `devbox run web`.
# Uses the web-server device, so no Chrome is needed; open the URL in any browser.
set -euo pipefail

PORT="${FLUTTER_WEB_PORT:-8890}"
# 127.0.0.1, not localhost: Dart binds "localhost" to IPv6 [::1] only. The
# dev container sets CONTACTHUB_BIND_HOST=0.0.0.0, so its forwarded port
# reaches the server. Browsers still reach it at http://localhost:$PORT/app/.
HOST="${CONTACTHUB_BIND_HOST:-127.0.0.1}"

cd "$(dirname "$0")/../contacthub_app"
source ../scripts/version.sh
# The dev server proxies /api/ to the local API (scripts/api.sh), so the app
# calls its own origin: no CORS, and it works behind a forwarded port
# (Codespaces) too. The bare root goes to the API as well, which redirects
# it to /app/, so a forwarded port's URL opens the app as it is. The dev
# server has no redirect of its own. web_dev_config.yaml is generated
# here, git-ignored.
cat > web_dev_config.yaml <<YAML
# Generated by scripts/flutter-web.sh: the dev server's proxy to the API.
server:
  proxy:
    - prefix: "/api/"
      target: "http://127.0.0.1:${API_PORT:-8891}/"
    - regex: "^/\$"
      target: "http://127.0.0.1:${API_PORT:-8891}/"
YAML
flutter pub get
# The welcome screen shows X.Y.Z, Z being when this server started.
# API_BASE_URL: empty, so the app calls /api/ on its own origin (the
# proxy above).
defines=(
  --dart-define="CONTACTHUB_VERSION=$VERSION"
  --dart-define="API_BASE_URL=${API_BASE_URL:-}"
)
# FLUTTER_WEB_MODE=release (the dev containers set it): a release build,
# served by scripts/web-server.dart with the same /api/ and root proxy.
# Through a codespace's forwarded port a debug build loads for minutes
# (its dart_sdk.js alone is 11 MB, uncompressed) and the page stays
# blank; a release build is a few MB, gzipped, and no compiler keeps
# running. The server answers at once with a page saying the app is
# building (503, so start-all.sh and the readiness probe wait), then the
# build. No hot reload in this mode.
if [[ "${FLUTTER_WEB_MODE:-debug}" == release ]]; then
  out="$PWD/build/web"
  rm -f "$out/.ready"
  WEB_ROOT="$out" WEB_HOST="$HOST" WEB_PORT="$PORT" API_PORT="${API_PORT:-8891}" \
    dart ../scripts/web-server.dart &
  server=$!
  trap 'kill "$server" 2>/dev/null' EXIT
  flutter build web --release --base-href /app/ "${defines[@]}"
  touch "$out/.ready"
  wait "$server"
  exit
fi
exec flutter run -d web-server --web-hostname "$HOST" --web-port "$PORT" \
  --base-href /app/ "${defines[@]}"
